// Drawing a block of LLM forecast text: the label, a row of reader tabs (Public, Industry,
// Expert), the text, and for forecasters what it was built from.
//
// The site only shows this text. It is written by a producer, checked at upload against the
// llm_forecast/1 contract (llmForecast.js), and read here through GET /api/llm-forecasts/latest,
// which hands over each persona's newest file or says there is none. Rules:
//
//  - Nothing is drawn until there is text to draw. A block whose file is missing, expired,
//    stale, or about an older model run than the chart beside it is not there at all: no
//    placeholder, no spinner, no "unavailable".
//  - Every block opens on Public, every time. Tabs are independent from block to block.
//  - It is always labelled "LLM forecast", with a line saying no forecaster wrote it. Persona
//    names never reach the page.
//  - The text goes in as text. Blank lines are paragraph breaks; nothing in it is run as HTML.

import { PERSONAS, parseUtc, placementText } from './llmForecast.js';
import { mountainTime } from './mountainTime.js';

export const LLM_LABEL = 'LLM forecast';
export const LLM_DISCLAIMER = 'Generated by an LLM from model and observation data. No forecaster wrote or checked it; '
    + 'verify with official forecasts.';
export const TIER_LABELS = { public: 'Public', industry: 'Industry', expert: 'Expert' };

const REFRESH_MS = 5 * 60 * 1000;
const utcHour = (ms) => `${String(new Date(ms).getUTCHours()).padStart(2, '0')}Z`;

/** "the GEFS 06Z run and the HRRR 09Z run, with observations to 4:50 AM", from a describes block. */
export function describesLine(describes, now) {
    const at = (key) => parseUtc(describes?.[key]);
    const runs = [];
    if (at('gefs') !== null) runs.push(`the GEFS ${utcHour(at('gefs'))} run`);
    if (at('hrrr') !== null) runs.push(`the HRRR ${utcHour(at('hrrr'))} run`);
    const through = [];
    if (at('obs_through') !== null) through.push(`observations to ${mountainTime(at('obs_through'), now)}`);
    if (at('aircraft_through') !== null) through.push(`aircraft data to ${mountainTime(at('aircraft_through'), now)}`);
    const parts = [runs.join(' and '), through.join(' and ')].filter(Boolean);
    return parts.length ? `Describes ${parts.join(', with ')}.` : '';
}

/**
 * Everything one block shows, or null when it shows nothing.
 * `{ label, disclaimer, tabs }`, each tab `{ tier, label, paragraphs, meta, sources }`.
 */
export function blockModel(placementKey, files, { now, chartGefs = null } = {}) {
    const text = placementText(placementKey, files, { now, chartGefs });
    if (!text) return null;
    return {
        label: LLM_LABEL,
        disclaimer: LLM_DISCLAIMER,
        tabs: text.tiers.map((entry) => ({
            tier: entry.tier,
            label: TIER_LABELS[entry.tier],
            paragraphs: entry.text.split(/\n\s*\n/).map((p) => p.replace(/\s*\n\s*/g, ' ').trim()).filter(Boolean),
            meta: [`Issued ${mountainTime(Date.parse(entry.issued), now)}.`, describesLine(entry.describes, now)].filter(Boolean).join(' '),
            // What it was built from is shown to forecasters, on the Expert tab only.
            sources: entry.tier === 'expert' ? entry.sources : [],
        })),
    };
}

// ── drawing ───────────────────────────────────────────────────────────────────────────────

let blockCount = 0;

function element(tag, className, text) {
    const el = document.createElement(tag);
    if (className) el.className = className;
    if (text !== undefined) el.textContent = text;
    return el;
}

function panelFor(tab, id, labelledBy) {
    const panel = element('div', 'llm-panel');
    panel.id = id;
    panel.setAttribute('role', 'tabpanel');
    panel.setAttribute('aria-labelledby', labelledBy);
    panel.tabIndex = 0;
    for (const paragraph of tab.paragraphs) panel.append(element('p', 'llm-text', paragraph));
    if (tab.sources.length > 0) {
        const built = element('div', 'llm-sources');
        built.append(element('span', 'llm-sources-title', 'Built from'));
        const list = element('ul');
        for (const source of tab.sources) list.append(element('li', '', source));
        built.append(list);
        panel.append(built);
    }
    panel.append(element('p', 'llm-meta', tab.meta));
    return panel;
}

/** Draw `model` into `container`, or empty and hide the container when the model is null. */
export function renderLlmBlock(container, model) {
    if (!model) {
        container.replaceChildren();
        container.hidden = true;
        return;
    }
    blockCount += 1;
    const prefix = `llm-${blockCount}`;
    const head = element('div', 'llm-head');
    head.append(element('h3', 'llm-label', model.label));

    // The tab row reuses the site's one tab style (.dashboard-tabs / .tab-button in main.css).
    const tablist = element('div', 'dashboard-tabs llm-tabs');
    tablist.setAttribute('role', 'tablist');
    tablist.setAttribute('aria-label', 'Written for');
    const panels = [];
    const buttons = model.tabs.map((tab, index) => {
        const button = element('button', 'tab-button', tab.label);
        button.type = 'button';
        button.id = `${prefix}-tab-${tab.tier}`;
        button.setAttribute('role', 'tab');
        button.setAttribute('aria-controls', `${prefix}-panel-${tab.tier}`);
        panels.push(panelFor(tab, `${prefix}-panel-${tab.tier}`, button.id));
        tablist.append(button);
        return button;
    });

    const select = (index, focus = false) => {
        buttons.forEach((button, i) => {
            const on = i === index;
            button.classList.toggle('active', on);
            button.setAttribute('aria-selected', String(on));
            button.tabIndex = on ? 0 : -1;
            panels[i].hidden = !on;
        });
        if (focus) buttons[index].focus();
    };
    buttons.forEach((button, index) => {
        button.addEventListener('click', () => select(index));
        button.addEventListener('keydown', (event) => {
            const step = { ArrowRight: 1, ArrowLeft: -1 }[event.key];
            if (step) {
                event.preventDefault();
                select((index + step + buttons.length) % buttons.length, true);
            } else if (event.key === 'Home' || event.key === 'End') {
                event.preventDefault();
                select(event.key === 'Home' ? 0 : buttons.length - 1, true);
            }
        });
    });
    select(0); // Public, or the first tier this placement has

    // One tier needs no tabs: a row with a single button is only noise.
    if (buttons.length > 1) head.append(tablist);
    container.replaceChildren(head, ...panels, element('p', 'llm-disclaimer', model.disclaimer));
    container.hidden = false;
}

/**
 * The newest file from each persona, or null for one that has none.
 *
 * One request to /api/llm-forecasts/latest, which answers 200 with a null for a persona that
 * has sent nothing. The files are not fetched by name: before any producer has sent one, that
 * would put a 404 in the console of every visitor to the homepage.
 */
export async function loadLlmFiles() {
    const none = Object.fromEntries(Object.keys(PERSONAS).map((persona) => [persona, null]));
    try {
        const response = await fetch('/api/llm-forecasts/latest', { cache: 'no-store' });
        if (!response.ok) return none;
        const files = (await response.json())?.files;
        return Object.fromEntries(Object.keys(none).map((persona) => [persona, files?.[persona] ?? null]));
    } catch {
        return none;
    }
}

/**
 * Keep every `[data-llm-placement]` element on the page up to date: drawn while its text is
 * current, gone when it is not. `getChartGefs` may return the GEFS cycle a page is charting.
 */
export function mountLlmBlocks({ getChartGefs = () => null } = {}) {
    const containers = [...document.querySelectorAll('[data-llm-placement]')];
    if (containers.length === 0) return;
    let shown = new Map();
    const refresh = async () => {
        const files = await loadLlmFiles();
        const now = Date.now();
        for (const container of containers) {
            const model = blockModel(container.dataset.llmPlacement, files, { now, chartGefs: getChartGefs() });
            // Redraw only when the words change, so a reader's chosen tab survives a refresh.
            const signature = model ? JSON.stringify(model.tabs.map((tab) => [tab.tier, tab.paragraphs, tab.meta])) : '';
            if (shown.get(container) === signature) continue;
            shown.set(container, signature);
            renderLlmBlock(container, model);
        }
    };
    refresh();
    setInterval(refresh, REFRESH_MS);
}

if (typeof document !== 'undefined' && document.querySelector('[data-llm-placement]')) {
    mountLlmBlocks();
}
